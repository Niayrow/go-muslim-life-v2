import * as React from "react";
import { cva, type VariantProps } from "class-variance-authority";

import { cn } from "@/lib/utils";

const badgeVariants = cva(
  "inline-flex items-center rounded-full border px-2.5 py-0.5 text-xs font-semibold transition-colors focus:outline-none focus:ring-2 focus:ring-ring focus:ring-offset-2",
  {
    variants: {
      variant: {
        default: "brand-chip border-transparent",
        cool: "brand-chip-cool border-transparent",
        secondary:
          "border-transparent bg-brand-panel-elevated text-brand-soft",
        outline: "border-brand-line text-brand-soft",
        success:
          "border-transparent bg-brand-success/15 text-brand-success",
        danger:
          "border-transparent bg-brand-danger/15 text-brand-danger",
      },
    },
    defaultVariants: {
      variant: "default",
    },
  }
);

function Badge({
  className,
  variant,
  ...props
}: React.ComponentProps<"div"> & VariantProps<typeof badgeVariants>) {
  return (
    <div
      data-slot="badge"
      className={cn(badgeVariants({ variant }), className)}
      {...props}
    />
  );
}

export { Badge, badgeVariants };
